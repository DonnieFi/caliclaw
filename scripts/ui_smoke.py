"""Isolated browser checks. Requires Playwright and its Chromium browser.

Run: python scripts/ui_smoke.py [screenshot-directory]
All API calls are fixtures; no model or printer is contacted.
"""
import base64
import sys
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

ROOT = Path(__file__).resolve().parents[1]

def main():
    with sync_playwright() as p:
        browser = p.chromium.launch(args=['--no-sandbox'])
        page = browser.new_page(viewport={'width': 1440, 'height': 1000}, reduced_motion='reduce')
        state = {'notes': [], 'chats': 0, 'camera_fail': False, 'printer_fail': False, 'camera_calls': 0}
        errors = []
        page.on('pageerror', lambda err: errors.append(str(err)))
        def route(req):
            path = req.request.url.split('workbench.test', 1)[-1].split('?')[0]
            if path == '/api/camera':
                state['camera_calls'] += 1
                if state['camera_fail']:
                    req.fulfill(status=503, json={'detail': 'http://private-host secret-key'})
                else:
                    # A real JPEG generated by the browser; the response contract stays JPEG.
                    req.fulfill(content_type='image/jpeg', body=jpeg)
            elif path == '/api/printer':
                if state['printer_fail']:
                    req.abort()
                else:
                    req.fulfill(json={'simulated': True, 'state': 'Idle', 'source': 'simulated', 'temperature': 24, 'bed_temperature': 22})
            elif path == '/api/project':
                req.fulfill(json={'name': 'Workshop', 'fit': state['notes'], 'keep': ['hole spacing'] if state['notes'] else []})
            elif path == '/api/stl/import':
                req.fulfill(json={'revision_id': 'import-test', 'stl_url': '/fixtures/cube.stl'})
            elif path == '/api/revisions':
                req.fulfill(json=[{'id': 'revision-test-1'}] if state['chats'] else [])
            elif path == '/api/fit':
                data = req.request.post_data_json
                if not data['note'].strip():
                    req.fulfill(status=400, json={'detail': 'A fit note is required.'})
                else:
                    state['notes'].append(data)
                    req.fulfill(json={'ok': True})
            elif path == '/api/chat':
                state['chats'] += 1
                req.fulfill(json={'reply': 'Revision ready.', 'tokens': None})
            elif path.startswith('/api/'):
                req.fulfill(status=404, json={})
            else:
                file = ROOT / 'web' / (path.lstrip('/') or 'index.html')
                req.fulfill(path=str(file)) if file.is_file() else req.fulfill(status=404)
        page.goto('about:blank')
        jpeg = base64.b64decode(page.evaluate("() => {const c=document.createElement('canvas'); c.width=320;c.height=180;const x=c.getContext('2d');x.fillStyle='#3a4048';x.fillRect(0,0,320,180);return c.toDataURL('image/jpeg').split(',')[1];}"))
        page.route('http://workbench.test/**', route)
        page.goto('http://workbench.test/')
        expect(page.locator('#pSource')).to_have_text('Simulated')
        page.wait_for_function('typeof window.loadSTL === "function"')
        page.locator('#stlFile').set_input_files(str(ROOT / 'web/fixtures/cube.stl'))
        expect(page.locator('#stageStatus')).to_contain_text('mm on the plate')
        page.locator('#tabChat').focus()
        page.keyboard.press('ArrowRight')
        expect(page.locator('#printerPane')).to_be_visible()
        expect(page.locator('#tabPrinter')).to_be_focused()
        expect(page.locator('#cam')).to_be_visible()
        page.wait_for_function('document.querySelector("#cam").naturalWidth > 0')
        for control in ['startBtn', 'pauseBtn', 'cancelBtn']:
            expect(page.locator('#' + control)).to_be_disabled()
        state['camera_fail'] = True
        page.evaluate('refreshCamera()')
        expect(page.locator('#camNote')).to_have_text('Snapshot unavailable.')
        expect(page.locator('#cam')).to_be_hidden()
        state['camera_fail'] = False
        state['printer_fail'] = True
        previous = state['camera_calls']
        page.evaluate('pollPrinter()')
        page.wait_for_function('document.querySelector("#cam").naturalWidth > 0 && !document.querySelector("#cam").hidden', timeout=8000)
        assert state['camera_calls'] > previous
        state['printer_fail'] = False
        page.locator('#tabChat').click()
        page.locator('.fit summary').click()
        page.locator('#fitBtn').click()
        expect(page.locator('#fitStatus')).to_have_text('A fit note is required.')
        page.locator('#fitNote').fill('Hole was 0.4 mm tight')
        page.locator('#fitKeep').fill('hole spacing')
        page.locator('#fitBtn').click()
        expect(page.locator('#fitList')).to_contain_text('Hole was 0.4 mm tight')
        page.locator('#input').fill('Revise the hole')
        page.locator('#input').press('Enter')
        expect(page.locator('#revList')).to_contain_text('revision-test-')
        expect(page.locator('.msg.user')).to_have_count(1)
        page.locator('#input').fill('Check the part')
        page.locator('#send').click()
        expect(page.locator('.msg.user')).to_have_count(2)
        expect(page.locator('#send')).to_be_enabled()
        assert state['chats'] == 2
        expect(page.locator('#fitList')).to_contain_text('Hole was 0.4 mm tight')
        assert not errors, errors
        shots = Path(sys.argv[1]) if len(sys.argv) > 1 else None
        if shots:
            shots.mkdir(parents=True, exist_ok=True)
        for width, height in [(1440, 1000), (900, 800), (390, 844), (320, 740)]:
            page.set_viewport_size({'width': width, 'height': height})
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), width
            for name in ['chat', 'printer']:
                page.evaluate('(name) => showPane(name)', name)
                if shots:
                    page.screenshot(path=str(shots / f'{name}-{width}.png'), full_page=True)
        # Capture arrival separately from populated regression state.
        page.set_viewport_size({'width': 1440, 'height': 1000})
        page.evaluate("sessionStorage.clear()")
        page.reload()
        expect(page.locator('#empty')).to_be_visible()
        page.wait_for_function('document.querySelector("#viewport canvas") && typeof window.loadSTL === "function"')
        page.wait_for_function('document.querySelector("#viewport canvas").width > 0')
        page.evaluate('loadSTL("/fixtures/pocket-caliclaw.stl", false)')
        if shots:
            page.screenshot(path=str(shots / 'arrival.png'), full_page=True)
        browser.close()
        print('UI checks passed: camera independence/failure, simulated controls, fit notes, single chat path, keyboard tabs, four viewport widths.')

if __name__ == '__main__':
    main()
